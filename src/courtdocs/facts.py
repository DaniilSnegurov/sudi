def document_text(blocks: list[Block]) -> str:
    lines, page = [], 0
    for b in blocks:
        if b.page != page:
            page = b.page
            lines.append(f"--- страница {page} ---")
        lines.append(b.text)
    return "\n".join(lines)


def ask(client: ModelClient, task: str, schema: dict, purpose: str, text: str, images: list[bytes] | None) -> dict:
    """Один узкий запрос. С изображениями задание ставится в конец общего для документа запроса."""
    if images:
        return client.chat_json(SYSTEM_FUSED, f"Текст OCR:\n{text}\n\nЗадание.\n{task}", schema, purpose, images)
    return client.chat_json(f"{_COMMON_TEXT}\n\n{task}", "Документ:\n" + text, schema, purpose)


def extract_facts(client: ModelClient, blocks: list[Block], images: list[bytes] | None = None, text: str | None = None) -> dict:
    text = text or document_text(blocks)
    facts = dict(ask(client, TASK_CASE, SCHEMA_CASE, "facts.case", text, images))
    facts.update(ask(client, TASK_PEOPLE, SCHEMA_PEOPLE, "facts.people", text, images))
    facts["money"] = ask(client, TASK_MONEY, SCHEMA_MONEY, "facts.money", text, images)
    return facts
