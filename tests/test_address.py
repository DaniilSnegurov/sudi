@pytest.mark.parametrize("raw,context,street,dom,kv", CASES)
def test_address_forms(raw, context, street, dom, kv):
    parts = parse_dbtr_adr(raw, context)
    assert (parts.street_column, parts.house, parts.flat) == (street, dom, kv)


def test_street_type_is_not_invented():
    # в тексте названа другая улица — тип для «Контурной» ничем не подтверждён
    parts = parse_dbtr_adr("643,,55,,,Тест,11 Контурная,26,53", "г. Тест, ул. 10-я Чередовая, д. 26, кв. 53")
    assert parts.street_column == "г Тест, Контурная 11-я"


def test_number_that_is_part_of_the_name_stays_in_place():
    assert parse_dbtr_adr("643,,55,,Тест,,40 лет Примеров,57,20").street_column == "г Тест, 40 лет Примеров"


def test_unknown_layout_is_not_guessed():
    assert parse_dbtr_adr("где-то в Тесте").layout == "unknown"
